import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import path from 'node:path';
import test from 'node:test';
import {readManifest} from '@beyond10x/docs-system/manifest';
import {declaredDocumentRoute, documentIdForRoute, renderSidebars} from '../scripts/sidebar-contract.mjs';

const fixtures = path.join(import.meta.dirname, 'fixtures');
const sidebarsOf = (source) => JSON.parse(source.replace(/^module\.exports = /, '').replace(/;\n$/, ''));

async function essV5() {
  // Docs System's own v5 rendering of ESS's curated website/sidebars.ts, read through its validator.
  return readManifest(path.join(fixtures, 'ess-v5.yaml'));
}

function registryFor(manifests) {
  return {surfaces: manifests.map((manifest) => ({name: manifest.repository.displayName ?? manifest.repository.id, repository: {id: manifest.repository.id}}))};
}

const harness = {
  schema: 'b10x-docs/v4',
  repository: {id: 'harness', displayName: 'Harness'},
  surfaces: [{id: 'docs', routeBase: '/docs/harness/', source: {root: '.', navigation: {group: 'Build', label: 'Harness', order: 0, sidebar: 'autogenerated'}}}],
};

test('a declared ESS sidebar renders its six categories, in order, as documents of the one docs instance', async () => {
  const ess = await essV5();
  const document = sidebarsOf(renderSidebars(registryFor([ess, harness]), [ess, harness]));
  const [outcome, allDocs, section] = document.project_ess;
  assert.deepEqual(outcome, {type: 'link', label: 'Start by outcome', href: '/start/'});
  assert.deepEqual(allDocs, {type: 'link', label: 'All technical docs', href: '/docs/'});
  assert.equal(section.label, 'ESS');
  assert.deepEqual(section.link, {type: 'doc', id: 'ess/index'});
  assert.deepEqual(section.items.map((category) => category.label), ['Start here', 'Concepts', 'Guides', 'Reference', 'Examples', 'Project status']);
  assert.ok(section.items.every((category) => category.type === 'category' && category.collapsed === false));
  assert.deepEqual(section.items[0].items, [
    {type: 'doc', id: 'ess/index'},
    {type: 'doc', id: 'ess/getting-started/index'},
  ]);
  assert.deepEqual(section.items[2].items.map((item) => item.id), [
    'ess/guides/write-a-specification/index',
    'ess/guides/generate-artifacts/index',
    'ess/guides/verify-conformance/index',
    'ess/guides/track-change/index',
    'ess/guides/synthesize/index',
    'ess/guides/check-infrastructure/index',
  ]);
  assert.deepEqual(section.items[4].items, [{type: 'doc', id: 'ess/examples/specification-to-contracts/index'}]);
  const serialized = JSON.stringify(document.project_ess);
  assert.doesNotMatch(serialized, /autogenerated/, 'a declared sidebar replaces the autogenerated entry');
  assert.doesNotMatch(serialized, /record-realization/, 'a menu-withheld document is left out of the tree');
  assert.deepEqual(document.project_harness[2].items, [{type: 'autogenerated', dirName: 'harness'}], 'an undeclared repository beside it is untouched');
});

