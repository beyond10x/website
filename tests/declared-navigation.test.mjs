test('a declared landing document is served at the route base, and every other document keeps its route', async () => {
  const ess = await essV5();
  const [surface] = ess.surfaces;
  assert.equal(declaredDocumentRoute(surface, 'docs/index.md'), '/docs/ess/');
  assert.equal(declaredDocumentRoute(surface, 'docs/concepts/overview.md'), '/docs/ess/concepts/overview/');
  const landingElsewhere = {...surface, source: {...surface.source, navigation: {...surface.source.navigation, landing: 'docs/getting-started.md'}}};
  assert.equal(declaredDocumentRoute(landingElsewhere, 'docs/getting-started.md'), '/docs/ess/');
  assert.equal(declaredDocumentRoute(landingElsewhere, 'docs/concepts/overview.md'), '/docs/ess/concepts/overview/');
  const undeclared = {routeBase: '/docs/harness/', source: {root: '.', navigation: {sidebar: 'autogenerated'}}};
  assert.equal(declaredDocumentRoute(undeclared, 'docs/getting-started.md'), '/docs/harness/getting-started/');
  assert.equal(declaredDocumentRoute(undeclared, 'README.md'), '/docs/harness/');

  const declared = {...landingElsewhere, source: {...landingElsewhere.source, navigation: {
    ...landingElsewhere.source.navigation,
    sidebar: [{label: 'Start here', items: ['docs/concepts/overview.md', 'docs/getting-started.md']}],
  }}};
  const manifest = {...ess, surfaces: [declared]};
  const document = sidebarsOf(renderSidebars(registryFor([manifest]), [manifest]));
  assert.deepEqual(document.project_ess[2].items, [{
    type: 'category',
    label: 'Start here',
    items: [{type: 'doc', id: 'ess/concepts/overview/index'}, {type: 'doc', id: 'ess/index'}],
  }], 'the landing leaf names the document at the route base; an undeclared collapsed state is left to Docusaurus');
});

