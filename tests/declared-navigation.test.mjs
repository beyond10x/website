test('declared navigation refusals: route base namespace, declared paths without a document, and a doubled landing route', async () => {
  const {declaredNavigationRefusals} = await import('../scripts/sidebar-contract.mjs');
  const ess = await essV5();
  const document = (relative) => ({repository: 'ess', surface: 'docs', kind: 'document', sourcePath: `website/${relative}`, outputPath: `ess/docs/document/${relative}`});
  const [surface] = ess.surfaces;
  const collected = ['docs/index.md', 'docs/getting-started.md', 'docs/guides/record-realization.md'];
  const leaves = (items) => items.flatMap((item) => (typeof item === 'string' ? [item] : leaves(item.items)));
  const all = [...new Set([...leaves(surface.source.navigation.sidebar), ...collected])].map(document);
  assert.deepEqual(declaredNavigationRefusals(ess, all), []);

  const missing = all.filter((file) => !['website/docs/concepts/ess.md', 'website/docs/guides/record-realization.md'].includes(file.sourcePath));
  assert.deepEqual(declaredNavigationRefusals(ess, missing), [
    'ess/docs sidebar leaf docs/concepts/ess.md is not a collected document',
    'ess/docs menu-withheld document docs/guides/record-realization.md is not a collected document',
  ]);
  const withSurface = (change) => ({...ess, surfaces: [change(structuredClone(surface))]});
  assert.deepEqual(declaredNavigationRefusals(withSurface((s) => ({...s, routeBase: '/docs/harness/ess/'})), all), ['ess/docs routeBase /docs/harness/ess/ is not at or below /docs/ess/']);
  assert.deepEqual(declaredNavigationRefusals(withSurface((s) => ({...s, routeBase: '/docs/ess-extra/'})), all), ['ess/docs routeBase /docs/ess-extra/ is not at or below /docs/ess/']);
  assert.deepEqual(declaredNavigationRefusals(withSurface((s) => ({...s, routeBase: '/docs/ess/lab/'})), all), []);
  const v3 = {schema: 'b10x-docs/v3', repository: {id: 'harness'}, surfaces: [{id: 'docs', routeBase: '/docs/eventlog/', source: {root: '.', documents: {include: ['docs/**']}}}]};
  assert.deepEqual(declaredNavigationRefusals(v3, []), ['harness/docs routeBase /docs/eventlog/ is not at or below /docs/harness/'], 'every manifest revision');
  const website = {schema: 'b10x-docs/v4', repository: {id: 'website'}, surfaces: [{id: 'site', routeBase: '/', source: {root: '.', documents: {include: ['README.md']}}}]};
  assert.deepEqual(declaredNavigationRefusals(website, []), [], "the Website's own / surface is the one exception");
  assert.deepEqual(declaredNavigationRefusals({...v3, repository: {id: 'website'}}, []), ['website/docs routeBase /docs/eventlog/ is not at or below /docs/website/']);
  assert.deepEqual(
    declaredNavigationRefusals(withSurface((s) => { s.source.navigation.landing = 'docs/getting-started.md'; return s; }), all),
    ['ess/docs landing docs/getting-started.md and website/docs/index.md both serve /docs/ess/'],
  );
  assert.deepEqual(
    declaredNavigationRefusals(withSurface((s) => { s.source.navigation.landing = 'docs/absent.md'; return s; }), all.filter((file) => file.sourcePath !== 'website/docs/index.md')),
    ['ess/docs sidebar leaf docs/index.md is not a collected document', 'ess/docs landing docs/absent.md is not a collected document'],
  );
});

