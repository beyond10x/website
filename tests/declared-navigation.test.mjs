test('the document at the route base cannot be menu-withheld, whether it is the index or a declared landing', async () => {
  const {declaredNavigationRefusals, isMenuWithheld} = await import('../scripts/sidebar-contract.mjs');
  const ess = await essV5();
  const [surface] = ess.surfaces;
  const document = (relative) => ({repository: 'ess', surface: 'docs', kind: 'document', sourcePath: `website/${relative}`, outputPath: `ess/docs/document/${relative}`});
  const withNavigation = (change) => {
    const changed = structuredClone(surface);
    change(changed.source.navigation);
    return {...ess, surfaces: [changed]};
  };
  const index = withNavigation((navigation) => {
    delete navigation.landing;
    navigation.menuWithheld = ['docs/index.md'];
    navigation.sidebar = [{label: 'Start here', items: ['docs/getting-started.md']}];
  });
  assert.deepEqual(declaredNavigationRefusals(index, ['docs/index.md', 'docs/getting-started.md'].map(document)), [
    'ess/docs menu-withheld document docs/index.md serves the route base /docs/ess/, which cannot be withheld',
  ]);
  const landing = withNavigation((navigation) => {
    navigation.landing = 'docs/getting-started.md';
    navigation.menuWithheld = ['docs/getting-started.md'];
    navigation.sidebar = [{label: 'Start here', items: ['docs/concepts/overview.md']}];
  });
  assert.deepEqual(declaredNavigationRefusals(landing, ['docs/getting-started.md', 'docs/concepts/overview.md'].map(document)), [
    'ess/docs menu-withheld document docs/getting-started.md serves the route base /docs/ess/, which cannot be withheld',
  ]);
  assert.equal(isMenuWithheld(surface, 'docs/guides/record-realization.md'), true);
  assert.equal(isMenuWithheld(surface, 'docs/index.md'), false);
});
